BATCH_COMBINATOR_FUNCTIONS="___batch0 ___help_manual0 ___help_manual_part1 ___report1 ___report_last2 ___report_since2 ___boot2 ___witness1 ___freeze1 ___freeze_ack1"
ANCHOR_STEM_TABLE="ANCHOR_STEM_unknown_command='_unknown_command1' ANCHOR_STEM_note='_note1' ANCHOR_STEM_comment='_comment1' ANCHOR_STEM_error='_error1 _error2 _error3' ANCHOR_STEM_fail='_fail2' ANCHOR_STEM_log='_log1 _log2 _log3' ANCHOR_STEM_database_dir_validated='_database_dir_validated2' ANCHOR_STEM_database_dir_create='_database_dir_create2' ANCHOR_STEM_version='_version0' ANCHOR_STEM_batch='_batch2 __batch1 ___batch0' ANCHOR_STEM_printenv='_printenv0' ANCHOR_STEM_help='_help0 _help1 _help2 _help3 _help4 _help5 _help6' ANCHOR_STEM_help_environment='_help_environment0' ANCHOR_STEM_help_manual_title='_help_manual_title0' ANCHOR_STEM_help_manual_part_print='_help_manual_part_print1' ANCHOR_STEM_help_manual_commands='_help_manual_commands0' ANCHOR_STEM_help_manual_environment='_help_manual_environment0' ANCHOR_STEM_complete='_complete0 _complete1 _complete2 _complete3 _complete4 _complete5 _complete6 _complete7 _complete8 _complete9' ANCHOR_STEM_report_render='_report_render3' ANCHOR_STEM_freeze_lines='_freeze_lines1' ANCHOR_STEM_freeze_clear='_freeze_clear1' ANCHOR_STEM_witness_lines='_witness_lines1' ANCHOR_STEM_wrong_arity='__wrong_arity1' ANCHOR_STEM_database_dir_ensure='__database_dir_ensure4' ANCHOR_STEM_database_dir_validate='__database_dir_validate4' ANCHOR_STEM_help_manual_part_exists='__help_manual_part_exists1' ANCHOR_STEM_report_stage_exists='__report_stage_exists1' ANCHOR_STEM_help_manual='___help_manual0' ANCHOR_STEM_help_manual_part='___help_manual_part1' ANCHOR_STEM_report='___report1' ANCHOR_STEM_report_last='___report_last2' ANCHOR_STEM_report_since='___report_since2' ANCHOR_STEM_boot='___boot2' ANCHOR_STEM_witness='___witness1' ANCHOR_STEM_freeze='___freeze1' ANCHOR_STEM_freeze_ack='___freeze_ack1'"
