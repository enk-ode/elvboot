# elvboot - the report over the kept boots of a stage: the owner's reading
# of what elvbootd kept, the witnesses' receipts and the chain of snapshots.
# Its own vocabulary (include/report.sh) on elebake's engine and database:
# the ELEBAKE_* variables name the same database, pins and templates; the
# stage vocabulary of elebake is not reachable from here.
#
# POSIX shell compliant (tested on FreeBSD sh).

# elebake.sh defines the engine, the modules and the shared constants; its
# main runs only under its own name. The tables it sets are replaced below
# by this harness's own (make metadata-elvboot regenerates them).
: "${ELEBAKE_CONTEXT_SCRIPT:=$(readlink -f "$0" 2>/dev/null || realpath "$0" 2>/dev/null || echo "$0")}"
ELEBAKE_CONTEXT_TOOL=elvboot
ELEBAKE_CONTEXT_TAGLINE="the report over the kept boots of a stage (elebake's database and engine)"
. "$(dirname "$ELEBAKE_CONTEXT_SCRIPT")/elebake.sh"
for _v in $(set | sed -n 's/^\(ANCHOR_STEM_[A-Za-z0-9_]*\)=.*/\1/p'); do unset "$_v"; done
unset _v

# === METADATA (generated by make metadata-elvboot; the vocabulary of this harness) ===
